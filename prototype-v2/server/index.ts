import 'dotenv/config';
import pg from 'pg';
import { postgresRepository } from './db.js';
import { GeminiAdapter } from './ai.js';
import { createApp } from './app.js';
if(process.env.V2_DATABASE_ISOLATED!=='true'||!process.env.DATABASE_URL_V2)throw new Error('Configure DATABASE_URL_V2 em ambiente isolado e V2_DATABASE_ISOLATED=true.');
const pepper=process.env.AUTH_PEPPER??'',signingKey=process.env.REVIEW_SIGNING_KEY??'';
if(pepper===signingKey)throw new Error('Segredos de autenticação e parecer devem ser diferentes.');
const pool=new pg.Pool({connectionString:process.env.DATABASE_URL_V2,max:5});
const app=createApp(postgresRepository(pool,pepper),new GeminiAdapter(),signingKey,{origin:process.env.PUBLIC_ORIGIN});
const server=app.listen(Number(process.env.API_PORT)||8787,process.env.API_HOST||'127.0.0.1',()=>console.log('API V2 pronta.'));
for(const signal of ['SIGTERM','SIGINT'] as const)process.on(signal,()=>server.close(()=>{void pool.end();}));
